const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const fs = require('fs');
(async()=>{
  const browser=await chromium.launch({headless:true,...(process.env.CHROME_PATH?{executablePath:process.env.CHROME_PATH}:{})});
  const evidence=[];
  try {
    const page=await browser.newPage({viewport:{width:1440,height:1100}});
    page.setDefaultTimeout(10000);
    const errors=[];page.on('pageerror',e=>errors.push(String(e)));
    await page.goto(process.env.BASE_URL||'http://127.0.0.1:8010');
    const actor=page.getByLabel('Acting administrator');
    await actor.selectOption('bob@west.test');
    await page.getByRole('cell',{name:'DEMO-WEST-001',exact:true}).waitFor();
    if(await page.getByRole('cell',{name:'DEMO-EAST-001',exact:true}).count()) throw Error('Cross-tenant row visible');
    await page.getByRole('button',{name:'Issue certificates',exact:true}).click();
    await page.getByRole('heading',{name:/Operation #/}).waitFor();
    const outcomes=await page.getByRole('status').last().innerText();
    if(!outcomes.includes('Alex Lee: issued')) throw Error('Fresh West issuance missing: '+outcomes);
    evidence.push('PASS: West browser issuance actually issued Alex Lee; per-learner outcomes shown.');
    await page.reload();
    await actor.selectOption('bob@west.test');
    await page.getByRole('cell',{name:'Alex Lee',exact:true}).waitFor();
    evidence.push('PASS: West certificate persisted across browser reload.');
    const search=page.getByLabel('Search learner or serial');
    await search.fill('Alex Lee'); await page.getByRole('button',{name:'Search / refresh'}).click();
    await page.getByRole('cell',{name:'Alex Lee',exact:true}).waitFor();
    await page.getByRole('button',{name:'View',exact:true}).click();
    await page.getByRole('button',{name:'Revoke certificate',exact:true}).waitFor();
    await page.getByRole('button',{name:'Revoke certificate',exact:true}).click();
    await page.getByRole('button',{name:'Cancel',exact:true}).click();
    await page.getByRole('button',{name:'Revoke certificate',exact:true}).click();
    await page.getByRole('button',{name:'Confirm revocation',exact:true}).click();
    await page.getByText('REVOKED · bob@west.test',{exact:false}).waitFor();
    evidence.push('PASS: revoke confirmation, cancel, confirm, status and audit refresh.');
    await search.fill('no-such-certificate-unique'); await page.getByRole('button',{name:'Search / refresh'}).click();
    await page.getByText('No certificates match your search.',{exact:true}).waitFor();
    evidence.push('PASS: empty state.');
    // Delay the real list route to make the loading state observable.
    await page.route('**/api/certificates?*',async route=>{await new Promise(r=>setTimeout(r,300));await route.continue();});
    await page.getByRole('button',{name:'Search / refresh'}).click();
    await page.getByText('Loading certificates…',{exact:true}).waitFor();
    await page.getByText('No certificates match your search.',{exact:true}).waitFor();
    await page.unroute('**/api/certificates?*');
    evidence.push('PASS: loading state.');
    await page.route('**/api/certificates?*',route=>route.fulfill({status:503,contentType:'application/json',body:'{"detail":"Verification service unavailable"}'}));
    await page.getByRole('button',{name:'Search / refresh'}).click();
    await page.getByText('Verification service unavailable',{exact:false}).waitFor();
    await page.unroute('**/api/certificates?*');
    await page.getByRole('button',{name:'Retry',exact:true}).click();
    await page.getByText('No certificates match your search.',{exact:true}).waitFor();
    evidence.push('PASS: API error state and successful retry.');
    await search.fill('DEMO-WEST');await page.getByRole('button',{name:'Search / refresh'}).click();
    await page.getByRole('cell',{name:'DEMO-WEST-001',exact:true}).waitFor();
    await page.getByLabel('Sort by').selectOption('serial_number');
    const [download]=await Promise.all([page.waitForEvent('download'),page.getByRole('button',{name:'Export CSV',exact:true}).click()]);
    const saved=await download.path();
    const csv=fs.readFileSync(saved,'utf8');
    if(!csv.includes('DEMO-WEST-001')||csv.includes('DEMO-EAST-001')||!csv.includes('2026-01-10')) throw Error('CSV tenant/filter/date mismatch');
    evidence.push('PASS: browser CSV download honors search and tenant-local date.');
    await page.screenshot({path:'verification/browser-scenarios.png',fullPage:true});
    if(errors.length) throw Error(errors.join('\n'));
    fs.writeFileSync('verification/browser-scenarios.txt',new Date().toISOString()+'\n'+evidence.join('\n')+'\n');
    console.log(evidence.join('\n'));
  } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exit(1)});
